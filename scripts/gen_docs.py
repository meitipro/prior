def page_contract(tree: ast.Module) -> str:
    rows = methods(tree)
    refs = refusals(tree)
    out = [front("Contract reference", "All ten methods of the Prior contract, generated from the source."), HEADER]
    out.append(
        "One contract, ten methods. Six write, four read. Money moves only in `withdraw`: `register` and `challenge` take it in, "
        "and `reveal`, `judge` and `close_entry` only move balances inside the contract.\n\n"
    )
    out.append("| Method | Kind | What it does |\n|---|---|---|\n")
    for m in rows:
        kind = {"write": "write", "payable": "write, payable", "view": "view"}[m["kind"]]
        summary = mdx_text(m["doc"].split(". ")[0].rstrip(".") + ".")
        out.append(f"| [`{m['name']}`](#{m['name'].replace('_', '-')}) | {kind} | {summary} |\n")
    out.append("\n")
    for m in rows:
        out.append(f"## {m['name']}\n\n")
        out.append(fence("python", m["signature"]))
        out.append(f"\n{mdx_text(m['doc'])}\n\n")
        mine = [r for r in refs if m["name"] in r["where"] and r["prefix"] == "E"]
        if mine:
            out.append("Refuses with:\n\n")
            for r in mine:
                out.append(f"- {mdx_text(r['text'])}\n")
            out.append("\n")
    out.append(
        f"The source is [`contracts/prior.py`]({REPO}/contracts/prior.py). `list_entries` takes an address (the entries it sealed, with its balance) or an empty string (everyone's). "
        "Every view answers `{\"found\": false}` for an unknown id instead of raising, and always carries `totals`.\n"
    )
    return "".join(out)


def page_errors(tree: ast.Module) -> str:
    refs = refusals(tree)
    out = [front("Errors", "Every sentence the contract refuses with, generated from the source."), HEADER]
    out.append(
        "A refusal is a deterministic `UserError` whose sentence starts with `[EXPECTED]`. Validators agree on it byte for byte, so the transaction is "
        "**ACCEPTED** with an execution error. The site and the scripts treat that as a refusal, never as success: success is an accepted status "
        "**and** a leader execution that returned.\n\n"
    )
    out.append(
        "A model answer that cannot be read is `[LLM_ERROR]`. It always disagrees, so the round rotates to a committee that can answer; "
        "nothing is settled by it.\n\n"
    )
    out.append("| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "E":
            where = ", ".join(f"`{w}`" for w in r["where"] if not w.startswith("_")) or ", ".join(f"`{w}`" for w in r["where"])
            out.append(f"| {mdx_text(r['text'])} | {where} |\n")
    out.append("\n## Unreadable model answers\n\n| Sentence | From |\n|---|---|\n")
    for r in refs:
        if r["prefix"] == "L":
            out.append(f"| `[LLM_ERROR]` {mdx_text(r['text'])} | {', '.join(f'`{w}`' for w in r['where'])} |\n")
    return "".join(out)


def page_hashing(tree: ast.Module) -> str:
    vectors = json.loads((ROOT / "tests" / "vectors.json").read_text(encoding="utf-8"))["vectors"]
    out = [front("Hashing", "How a seal is computed, with test vectors the contract and the browser both pass."), HEADER]
    out.append("A seal is the sha256 of your text, a salt and your address, so the chain can date a description without seeing it. The contract and the browser compute the same bytes, and both are held to the vectors below.\n\n")
    out.append("## The bytes\n\n")
    out.append("The digest runs over the UTF-8 bytes of `text`, a bar, `salt`, a bar and the lower-case address with `0x`. The text is exactly as written: no trimming, no line-ending changes. The salt carries no bar, and neither does the address, so the join is unambiguous however many bars the text holds.\n\n")
    out.append(fence("python", ast.get_source_segment(CONTRACT.read_text(encoding="utf-8"), next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "seal_hash")) or "", "contracts/prior.py"))
    out.append("\nThe same in JavaScript, which is the code the site runs:\n\n")
    out.append(fence("js", (EXAMPLES / "seal-a-text.mjs").read_text(encoding="utf-8").split("*/", 1)[1], "web/examples/seal-a-text.mjs"))
    out.append("\n## Test vectors\n\nWritten by `scripts/gen_vectors.py` from the contract's own function. `node web/scripts/hash-parity.mjs` and the test suite check the browser code against them.\n\n")
    out.append("| Case | Address | Salt | Seal |\n|---|---|---|---|\n")
    for v in vectors:
        salt = v["salt"] if v["salt"] else "(empty)"
        short = salt if len(salt) <= 12 else salt[:11] + "…"
        out.append(f"| {mdx_text(v['name'])} | `{v['address'][:10]}…` | {mdx_text(short)} | `{v['seal']}` |\n")
    out.append(f"\nThe full inputs are in [`tests/vectors.json`]({REPO}/tests/vectors.json).\n")
    return "".join(out)


