    out.append("<Steps>\n<Step>\n\n**Stake.** 5 GEN, sent with `challenge`.\n\n</Step>\n<Step>\n\n**Read.** Anyone calls `judge`. The validators see two texts and no dates or names, and answer SUBSTANTIAL, PARTIAL or NONE.\n\n</Step>\n<Step>\n\n**Mark.** The contract derives the verdict from the label and the seal dates and credits balances by rule.\n\n</Step>\n<Step>\n\n**Withdraw.** The only call that pays is `withdraw`, in its own transaction.\n\n</Step>\n</Steps>\n\n## Reading an entry\n\n")
