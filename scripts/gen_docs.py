def site_data(tree: ast.Module) -> str:
    data = {
        "limits": limits(tree),
        "judge": constant(tree, "JUDGE"),
        "judge_sha256": hashlib.sha256(constant(tree, "JUDGE").encode("utf-8")).hexdigest(),
        "methods": [{k: m[k] for k in ("name", "kind", "signature", "doc")} for m in methods(tree)],
    }
    return json.dumps(data, indent=2, ensure_ascii=False, sort_keys=True) + "\n"


def targets() -> dict[pathlib.Path, str]:
    _, tree = load()
    return {
        DOCS / "reference" / "contract.mdx": page_contract(tree),
        DOCS / "reference" / "errors.mdx": page_errors(tree),
        DOCS / "reference" / "hashing.mdx": page_hashing(tree),
        DOCS / "reference" / "addresses.mdx": page_addresses(),
        DOCS / "more" / "judge-prompt.mdx": page_judge(tree),
        DOCS / "more" / "evaluation.mdx": page_evaluation(),
        DOCS / "quickstart.mdx": page_quickstart(),
        DOCS / "challenge-a-copy.mdx": page_challenge(),
        ROOT / "web" / "lib" / "contract.generated.json": site_data(tree),
    }


def main() -> int:
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    wanted = targets()
    # The examples must name the deployed contract, or a sample would send people to the wrong place.
    entry = frozen()
    if entry:
        for example in list(EXAMPLES.glob("*.mjs")) + list(EXAMPLES.glob("*.py")):
            text = example.read_text(encoding="utf-8")
            for found in re.findall(r"PRIOR\s*=\s*.(0x[0-9a-fA-F]{40})", text):
                if found != entry["prior"]:
                    print(f"{example.relative_to(ROOT).as_posix()} names {found}, not the deployed contract {entry['prior']}")
                    return 1
    if "--check" in sys.argv:
        stale = [p for p, text in wanted.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
        for p in stale:
            print("stale:", p.relative_to(ROOT).as_posix())
        if stale:
            print("run: python scripts/gen_docs.py")
            return 1
        print(f"{len(wanted)} generated files match the source")
        return 0
    for path, text in wanted.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote", path.relative_to(ROOT).as_posix())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
