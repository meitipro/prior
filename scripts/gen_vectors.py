#!/usr/bin/env python3
"""
Write tests/vectors.json: seals produced by the contract's own seal_hash.

    python scripts/gen_vectors.py           # write it
    python scripts/gen_vectors.py --check   # exit 1 when the file is not what the contract produces

A seal is sha256 over the UTF-8 bytes of "text|salt|address", the address
lower-case with 0x. The site computes the same bytes in the browser, and
web/scripts/hash-parity.mjs holds its answer to this file.
"""

from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tests"))

from harness import load  # noqa: E402
import genvm_double as D  # noqa: E402

OUT = ROOT / "tests" / "vectors.json"
ADA = "0x3e8b3e8b3e8b3e8b3e8b3e8b3e8b3e8b3e8b41aa"
CASES = [
    ("plain", "A weekly newsletter on votes.", "s1", ADA),
    ("the build spec entry", "A weekly newsletter that turns each governance vote into plain language and adds a table of how the ten largest holders voted, with a note when a holder voted against their usual side.", "k7f2", ADA),
    ("checksummed address", "Same text", "salt", "0x3E8B3E8B3E8B3E8B3E8B3E8B3E8B3E8B3E8B41AA"),
    ("bars in the text", "a|b|c|", "salt", ADA),
    ("empty salt", "text", "", ADA),
    ("persian", "خبرنامه‌ای هفتگی که هر رأی حاکمیتی را ساده می‌کند", "نمک"[:0] or "s", ADA),
    ("emoji and astral characters", "Launch \U0001f680 \U0001d54f math", "s", ADA),
    ("windows line endings", "line one\r\nline two\nline three", "s", ADA),
    ("surrounding whitespace is part of the text", "  padded \n", "s", ADA),
    ("a long text", "x" * 1500, "s" * 100, ADA),
    ("another address", "text", "s", "0x77d077d077d077d077d077d077d077d077d019c3"),
]


def build() -> dict:
    mod = load(D.GL())
    return {
        "about": "Seals as the contract computes them. See seal_hash in contracts/prior.py. Generated by scripts/gen_vectors.py.",
        "hash": "sha256 over the UTF-8 bytes of text + '|' + salt + '|' + address.lower()",
        "vectors": [{"name": n, "text": t, "salt": s, "address": a, "seal": mod.seal_hash(t, s, a)} for n, t, s, a in CASES],
    }


def main() -> int:
    text = json.dumps(build(), indent=2, ensure_ascii=False) + "\n"
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("tests/vectors.json is not what the contract produces. Run: python scripts/gen_vectors.py")
            return 1
        print("tests/vectors.json matches the contract")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote tests/vectors.json ({len(json.loads(text)['vectors'])} vectors)")
    return 0


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    raise SystemExit(main())
